#!/usr/bin/env node
/**
 * Generate the embedded MCP worker runtime for the compiled CLI binary.
 *
 * `trove mcp deploy` bundles a user's `server.ts` for the hosted runtime. In the
 * Bun single-binary distribution there is no on-disk `@ontrove/mcp` to bundle
 * (it is embedded in the binary), so we pre-bundle `@ontrove/mcp` — with its deps
 * (`zod`) — into one self-contained worker-target module
 * once, at build time, and embed the result as a string. The deploy bundler then
 * supplies it to `Bun.build` via a resolver plugin.
 *
 * This runs at BUILD time only (esbuild is a devDependency); the shipped binary
 * contains no esbuild and no bundler toolchain — it uses Bun natively.
 *
 * Output: `packages/trove-cli/src/vendor/mcp-worker-runtime.js`, an ESM module
 * `export default "<bundled source>"`. It is a git-ignored build artifact;
 * `mcp-worker-runtime.d.ts` is the committed type shim. Requires `@ontrove/mcp`
 * to be built first (the monorepo build order guarantees this).
 *
 * @module
 */
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const CLI_PKG = join(ROOT, 'packages', 'trove-cli', 'package.json');
const MCP_ENTRY = join(ROOT, 'packages', 'trove-extend', 'dist', 'toolkit', 'index.js');
const CLI_SRC_VENDOR = join(ROOT, 'packages', 'trove-cli', 'src', 'vendor');
const CLI_DIST_VENDOR = join(ROOT, 'packages', 'trove-cli', 'dist', 'vendor');
// Emit to src/vendor (consumed when Bun compiles the single binary) AND
// dist/vendor (shipped in the npm tarball, imported at runtime by the compiled
// `dist/lib/bundle.js` for `trove mcp deploy`). The committed `.d.ts` shim is
// copied alongside so the published `dist` types resolve.
const OUT = join(CLI_SRC_VENDOR, 'mcp-worker-runtime.js');

// esbuild is the CLI's build-time bundler (a devDependency); resolve it from the
// CLI package so this script works regardless of hoisting.
const require = createRequire(CLI_PKG);
const { build } = require('esbuild');

const result = await build({
  entryPoints: [MCP_ENTRY],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  conditions: ['workerd', 'worker', 'browser'],
  minify: true,
  write: false,
});

if (result.errors.length > 0) {
  console.error('Failed to bundle @ontrove/mcp for the worker target:');
  for (const e of result.errors) console.error(e.text);
  process.exit(1);
}

const source = result.outputFiles[0].text;
const banner =
  '// GENERATED by scripts/build-mcp-worker-runtime.mjs — do not edit.\n' +
  '// Pre-bundled @ontrove/mcp (worker target) embedded for `trove mcp deploy`.\n';
const module = `${banner}export default ${JSON.stringify(source)};\n`;

const { copyFileSync, existsSync, mkdirSync, writeFileSync } = await import('node:fs');
mkdirSync(CLI_SRC_VENDOR, { recursive: true });
writeFileSync(OUT, module);

// Also emit into dist/vendor so the runtime ships in the npm tarball. dist/ may
// not exist yet if this runs before tsc; create it. Copy the committed .d.ts
// shim so the published types resolve next to the .js.
mkdirSync(CLI_DIST_VENDOR, { recursive: true });
writeFileSync(join(CLI_DIST_VENDOR, 'mcp-worker-runtime.js'), module);
const dts = join(CLI_SRC_VENDOR, 'mcp-worker-runtime.d.ts');
if (existsSync(dts)) copyFileSync(dts, join(CLI_DIST_VENDOR, 'mcp-worker-runtime.d.ts'));

console.log(`✓ wrote ${OUT} and dist/vendor (${source.length} bytes of bundled runtime)`);
