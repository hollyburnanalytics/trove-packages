#!/usr/bin/env bun
/**
 * Generate the Homebrew formula for `trove` from the packaged release archives.
 *
 * Usage: bun scripts/gen-homebrew-formula.mjs <version>
 *   e.g. bun scripts/gen-homebrew-formula.mjs v0.2.0
 *
 * Reads the four macOS/Linux `*.tar.gz` archives in `dist/bin/`, computes their
 * SHA-256, and writes `packaging/homebrew/trove.rb` pointing at the matching
 * GitHub Release assets. In CI this runs after the archives are built; the
 * output is committed/pushed to the Homebrew tap repo (owner per your tap
 * decision — the formula URLs point at hollyburnanalytics/trove-packages
 * releases regardless of who owns the tap).
 *
 * @module
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const version = process.argv[2];
if (!version) {
  console.error('usage: bun scripts/gen-homebrew-formula.mjs <version>');
  process.exit(1);
}

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const BIN = join(ROOT, 'dist', 'bin');
const OUT = join(ROOT, 'packaging', 'homebrew', 'trove.rb');
const REPO = 'hollyburnanalytics/trove-packages';

const sha256 = (file) => createHash('sha256').update(readFileSync(join(BIN, file))).digest('hex');

const A = {
  darwinArm: 'trove-darwin-arm64.tar.gz',
  darwinX64: 'trove-darwin-x64.tar.gz',
  linuxX64: 'trove-linux-x64.tar.gz',
  linuxArm: 'trove-linux-arm64.tar.gz',
};
// The download URL embeds the full release tag (`@ontrove/cli@x.y.z` from
// Changesets, or a manual `vX.Y.Z`). GitHub percent-encodes only `@` → `%40` in
// the tag path segment and leaves the `/` literal, e.g.
// `…/download/%40ontrove/cli%400.3.0/…`. Match that exactly (encodeURIComponent
// would wrongly escape the `/` too and 404).
const tagPath = version.replace(/@/g, '%40');
const url = (asset) => `https://github.com/${REPO}/releases/download/${tagPath}/${asset}`;
// The formula `version` field and its `--version` test need the bare semver,
// extracted from either tag shape: `@ontrove/cli@0.3.0` or `v0.3.0` → `0.3.0`.
const bare = version.includes('@') ? version.slice(version.lastIndexOf('@') + 1) : version.replace(/^v/, '');

const formula = `# GENERATED by scripts/gen-homebrew-formula.mjs — do not edit by hand.
class Trove < Formula
  desc "The Trove command-line tool — knowledge base client + source/toolkit toolchain"
  homepage "https://ontrove.sh"
  version "${bare}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url(A.darwinArm)}"
      sha256 "${sha256(A.darwinArm)}"
    end
    on_intel do
      url "${url(A.darwinX64)}"
      sha256 "${sha256(A.darwinX64)}"
    end
  end

  on_linux do
    on_arm do
      url "${url(A.linuxArm)}"
      sha256 "${sha256(A.linuxArm)}"
    end
    on_intel do
      url "${url(A.linuxX64)}"
      sha256 "${sha256(A.linuxX64)}"
    end
  end

  def install
    bin.install Dir["trove-*"].first => "trove"
    prefix.install Dir["LICENSE", "THIRD-PARTY-LICENSES.txt"]
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/trove --version")
  end
end
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, formula);
console.log(`✓ wrote ${OUT} for ${version}`);
