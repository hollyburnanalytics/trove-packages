#!/usr/bin/env node
/**
 * Generate the embedded source worker runtime for the compiled CLI binary.
 *
 * The sibling of `build-mcp-worker-runtime.mjs`, for the other deployable. That
 * one pre-bundles `@ontrove/mcp` so `trove mcp deploy` can wrap a `server.ts`;
 * this one pre-bundles the source shim (`src/runtime/source-shim.ts`, which
 * pulls in `@ontrove/sdk`'s `runSource`) so `trove source deploy` can wrap an
 * `index.ts`. In the Bun single-binary distribution there is no on-disk
 * `@ontrove/sdk` to bundle at deploy time — it is embedded in the binary — so
 * the runtime is bundled once, here, for the worker target, and the deploy
 * bundler supplies it to `Bun.build` through a resolver plugin.
 *
 * This runs at BUILD time only (esbuild is a devDependency); the shipped binary
 * contains no esbuild and no bundler toolchain — it uses Bun natively.
 *
 * Output: `packages/trove-cli/src/vendor/source-worker-runtime.js`, an ESM
 * module `export default "<bundled source>"`. It is a git-ignored build
 * artifact; `source-worker-runtime.d.ts` is the committed type shim. Requires
 * `@ontrove/sdk` to be built first (the monorepo build order guarantees this).
 *
 * @module
 */
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const CLI_PKG = join(ROOT, 'packages', 'trove-cli', 'package.json');
const SHIM_ENTRY = join(ROOT, 'packages', 'trove-cli', 'src', 'runtime', 'source-shim.ts');
const SDK_ENTRY = join(ROOT, 'packages', 'trove-extend', 'dist', 'source', 'index.js');
const CLI_SRC_VENDOR = join(ROOT, 'packages', 'trove-cli', 'src', 'vendor');
const CLI_DIST_VENDOR = join(ROOT, 'packages', 'trove-cli', 'dist', 'vendor');
// Emit to src/vendor (consumed when Bun compiles the single binary) AND
// dist/vendor (shipped in the npm tarball, imported at runtime by the compiled
// `dist/lib/bundle.js` for `trove source deploy`). The committed `.d.ts` shim is
// copied alongside so the published `dist` types resolve.
const OUT = join(CLI_SRC_VENDOR, 'source-worker-runtime.js');

// Named explicitly rather than left to node resolution, so a workspace where
// the SDK has not been built yet fails here — with the reason — instead of
// producing a bundle against a stale `dist`.
if (!existsSync(SDK_ENTRY)) {
  console.error(`${SDK_ENTRY} does not exist — build @ontrove/sdk first (bun run build).`);
  process.exit(1);
}

// esbuild is the CLI's build-time bundler (a devDependency); resolve it from the
// CLI package so this script works regardless of hoisting.
const require = createRequire(CLI_PKG);
const { build } = require('esbuild');

const result = await build({
  entryPoints: [SHIM_ENTRY],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  conditions: ['workerd', 'worker', 'browser'],
  alias: { '@ontrove/sdk': SDK_ENTRY },
  minify: true,
  write: false,
});

if (result.errors.length > 0) {
  console.error('Failed to bundle the source shim for the worker target:');
  for (const e of result.errors) console.error(e.text);
  process.exit(1);
}

const source = result.outputFiles[0].text;
const banner =
  '// GENERATED by scripts/build-source-worker-runtime.mjs — do not edit.\n' +
  '// Pre-bundled source shim + @ontrove/sdk (worker target) for `trove source deploy`.\n';
const module = `${banner}export default ${JSON.stringify(source)};\n`;

mkdirSync(CLI_SRC_VENDOR, { recursive: true });
writeFileSync(OUT, module);

// Also emit into dist/vendor so the runtime ships in the npm tarball. dist/ may
// not exist yet if this runs before tsc; create it. Copy the committed .d.ts
// shim so the published types resolve next to the .js.
mkdirSync(CLI_DIST_VENDOR, { recursive: true });
writeFileSync(join(CLI_DIST_VENDOR, 'source-worker-runtime.js'), module);
const dts = join(CLI_SRC_VENDOR, 'source-worker-runtime.d.ts');
if (existsSync(dts)) copyFileSync(dts, join(CLI_DIST_VENDOR, 'source-worker-runtime.d.ts'));

console.log(`✓ wrote ${OUT} and dist/vendor (${source.length} bytes of bundled runtime)`);
